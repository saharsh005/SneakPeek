"""
recognizer.py
-------------
InsightFace face recognition — classifies each detected person as
known (enrolled) or unknown.

Why InsightFace over DeepFace here:
  - InsightFace runs faster on CPU (ArcFace backbone via ONNX)
  - DeepFace is kept available in enroll.py for enrollment flexibility
  - Both produce 512-d embeddings; cosine similarity is used for matching

The known face embeddings are loaded from data/embeddings.pkl which is
generated by setup/enroll.py before the system starts monitoring.

For each person bounding box from YOLOv8, this module:
  1. Crops and aligns the face region
  2. Computes embedding
  3. Compares against all enrolled embeddings via cosine similarity
  4. Returns "known" + name if above threshold, else "unknown"
"""

import cv2
import pickle
import numpy as np
import logging
import time
from pathlib import Path
from insightface.app import FaceAnalysis

logger = logging.getLogger(__name__)

EMBEDDINGS_PATH = Path("data/embeddings.pkl")


class FaceRecognizer:
    def __init__(self, config: dict):
        self._threshold = float(config["thresholds"]["face_similarity_min"])
        self._single_identity_relaxed = max(0.35, self._threshold - 0.12)
        self._last_reload_check = 0.0
        self._emb_mtime = 0.0

        logger.info("[recognizer] Loading InsightFace — first run downloads ONNX models")
        self._app = FaceAnalysis(
            name="buffalo_sc",          # lightweight model — good CPU performance
            providers=["CPUExecutionProvider"]
        )
        self._app.prepare(ctx_id=0, det_size=(320, 320))
        logger.info("[recognizer] InsightFace ready")

        self._known: dict[str, np.ndarray] = self._load_embeddings()
        logger.info(
            "[recognizer] face_similarity_min=%.3f, single-id relaxed=%.3f",
            self._threshold, self._single_identity_relaxed
        )

    # ------------------------------------------------------------------
    # Public API
    # ------------------------------------------------------------------
    def recognize_all(self, frame: np.ndarray) -> list[dict]:
        """
        Run face recognition on the full frame.

        Returns
        -------
        List of face results:
            {
                "name"      : str,       # enrolled name or "unknown"
                "known"     : bool,
                "similarity": float,     # best cosine similarity score
                "bbox"      : [x1,y1,x2,y2],
            }
        """
        self._maybe_reload_embeddings()
        faces = self._app.get(frame)
        results = []

        for face in faces:
            emb  = self._normalize(face.embedding)
            bbox = list(map(int, face.bbox.tolist()))
            name, sim = self._match(emb)
            results.append({
                "name":       name,
                "known":      name != "unknown",
                "similarity": round(sim, 3),
                "bbox":       bbox,
            })
            logger.debug(f"[recognizer] Face: {name} (sim={sim:.3f})")

        return results

    def unknown_count(self, face_results: list[dict]) -> int:
        return sum(1 for f in face_results if not f["known"])

    def reload_embeddings(self) -> None:
        """Hot-reload embeddings without restarting (call after new enrollment)."""
        self._known = self._load_embeddings()
        try:
            self._emb_mtime = EMBEDDINGS_PATH.stat().st_mtime
        except Exception:
            pass
        logger.info(f"[recognizer] Reloaded {len(self._known)} known identities")

    # ------------------------------------------------------------------
    # Internal helpers
    # ------------------------------------------------------------------
    def _match(self, embedding: np.ndarray) -> tuple[str, float]:
        """Return (name, similarity) for best matching known face."""
        if not self._known:
            return "unknown", 0.0

        best_name = "unknown"
        best_sim  = 0.0

        for name, known_emb in self._known.items():
            sim = self._cosine_similarity(embedding, known_emb)
            if sim > best_sim:
                best_sim  = sim
                best_name = name

        if best_sim < self._threshold:
            if len(self._known) == 1 and best_sim >= self._single_identity_relaxed:
                logger.debug("[recognizer] relaxed single-id accept: %s sim=%.3f", best_name, best_sim)
                return best_name, best_sim
            return "unknown", best_sim

        return best_name, best_sim

    @staticmethod
    def _cosine_similarity(a: np.ndarray, b: np.ndarray) -> float:
        denom = (np.linalg.norm(a) * np.linalg.norm(b))
        if denom == 0:
            return 0.0
        return float(np.dot(a, b) / denom)

    @staticmethod
    def _normalize(v: np.ndarray) -> np.ndarray:
        n = np.linalg.norm(v)
        if n == 0:
            return v
        return v / n

    def _maybe_reload_embeddings(self) -> None:
        now = time.time()
        if now - self._last_reload_check < 2.0:
            return
        self._last_reload_check = now
        if not EMBEDDINGS_PATH.exists():
            return
        try:
            mtime = EMBEDDINGS_PATH.stat().st_mtime
        except Exception:
            return
        if mtime > self._emb_mtime:
            self.reload_embeddings()

    @staticmethod
    def _load_embeddings() -> dict[str, np.ndarray]:
        if not EMBEDDINGS_PATH.exists():
            logger.warning(
                "[recognizer] No embeddings found at data/embeddings.pkl — "
                "run setup/enroll.py first. Everyone will appear as unknown."
            )
            return {}
        with open(EMBEDDINGS_PATH, "rb") as f:
            data = pickle.load(f)
        normalized: dict[str, np.ndarray] = {}
        for name, emb in data.items():
            emb_np = np.asarray(emb, dtype=np.float32)
            n = np.linalg.norm(emb_np)
            normalized[name] = emb_np if n == 0 else emb_np / n
        logger.info(f"[recognizer] Loaded embeddings for: {list(normalized.keys())}")
        return normalized
